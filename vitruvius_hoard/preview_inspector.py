"""Elements a person selected on an application preview, kept for the agent.

The inspector script (``preview_scripts/preview-inspector.js``) runs inside the owned preview and reports each element it
selected to the Vitruvius page that frames it. That page stores the list here, so an agent can read "this" without
the person describing it. The list is advisory: it is per project, in memory, and replaced on every report.
"""
from __future__ import annotations

import threading
import time
from pathlib import Path

MAX_SELECTION = 24
MAX_TEXT = 200
_SCRIPT = Path(__file__).with_name("preview_scripts") / "preview-inspector.js"
_BOX = ("x", "y", "w", "h")


def inspector_script() -> str:
    """The inspector's source, for the code that injects scripts into the preview."""
    return _SCRIPT.read_text(encoding="utf-8")


def _text(value, limit):
    return value[:limit] if isinstance(value, str) else None


def _number(value):
    return value if isinstance(value, (int, float)) and not isinstance(value, bool) else 0


def _item(raw):
    if not isinstance(raw, dict) or not isinstance(raw.get("selector"), str) or not raw["selector"].strip():
        return None
    vsrc = _text(raw.get("vsrc"), 300) or None
    vgen = _text(raw.get("vgen"), 80) or None
    count = raw.get("same_vsrc_count")
    count = count if isinstance(count, int) and not isinstance(count, bool) and count >= 0 else 0
    item = {
        "selector": raw["selector"][:500], "tag": (_text(raw.get("tag"), 40) or "").lower(),
        "classes": [c[:60] for c in raw.get("classes", []) if isinstance(c, str)][:12] if isinstance(raw.get("classes"), list) else [],
        "text": _text(raw.get("text"), MAX_TEXT) or "",
        "box": {key: _number((raw.get("box") or {}).get(key)) for key in _BOX} if isinstance(raw.get("box"), dict) else dict.fromkeys(_BOX, 0),
        "computed": {str(k)[:40]: str(v)[:120] for k, v in list(raw["computed"].items())[:16]} if isinstance(raw.get("computed"), dict) else {},
        "vsrc": vsrc, "vgen": vgen, "same_vsrc_count": count,
    }
    if vsrc:
        file, _, rest = vsrc.partition(":")
        line, _, column = rest.partition(":")
        if line.isdigit() and column.isdigit():
            item.update({"file": file, "line": int(line), "column": int(column)})
    if count > 1:
        item["affects"] = f"{count} elements share this source position"
    if vgen:
        item["generated_by"] = "{{" + vgen + "}}"
        item["note"] = f"Generated by {{{{{vgen}}}}}: change it in the project fields or styles, not in the HTML."
    elif not vsrc:
        item["note"] = "No source position: the page did not annotate this element."
    return item


def normalise(selection):
    """Validate a selection reported by the page: bounded, typed, and without items that name no element."""
    if not isinstance(selection, list):
        raise ValueError("selection must be a list")
    return [item for item in map(_item, selection[:MAX_SELECTION]) if item]


class PreviewSelections:
    def __init__(self):
        self._lock = threading.Lock()
        self._by_project = {}

    def set(self, project_id, selection, revision=None):
        items = normalise(selection)
        entry = {"id": project_id, "selection": items, "count": len(items), "revision": revision, "updated_ts": time.time()}
        with self._lock:
            if items:
                self._by_project[project_id] = entry
            else:
                self._by_project.pop(project_id, None)
        return entry if items else self.get(project_id, revision)

    def get(self, project_id, revision=None):
        with self._lock:
            entry = self._by_project.get(project_id)
        if entry:
            return dict(entry)
        return {"id": project_id, "selection": [], "count": 0, "revision": revision, "updated_ts": None,
                "note": "Nothing is selected in the open preview. The person selects elements with Select on the preview."}


def read_selection(services, project_id, revision=None):
    """Current selection of an existing project (an unknown project is a LookupError, like the other project tools)."""
    services.app_projects._directory(project_id)
    return services.preview_selections.get(project_id, revision)


def write_selection(services, project_id, selection, revision=None):
    services.app_projects._directory(project_id)
    return services.preview_selections.set(project_id, selection, revision)
