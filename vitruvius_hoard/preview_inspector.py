"""Elements a person selected on an application preview, kept for the agent.

The inspector script (``preview_scripts/preview-inspector.js``) runs inside the owned preview and reports each element it
selected to the Vitruvius page that frames it. That page stores the list here, so an agent can read "this" without
the person describing it. The list is advisory: it is per project, in memory, and replaced on every report.
"""
from __future__ import annotations

import copy
import threading
import time
from pathlib import Path

MAX_SELECTION = 24
MAX_TEXT = 200
MAX_HTML = 1200
MAX_CLIP = 150_000
_SCRIPT = Path(__file__).with_name("preview_scripts") / "preview-inspector.js"
_BOX = ("x", "y", "w", "h")


def inspector_script() -> str:
    """The inspector's source, for the code that injects scripts into the preview."""
    return _SCRIPT.read_text(encoding="utf-8")


def _text(value, limit):
    return value[:limit] if isinstance(value, str) else None


def _number(value):
    return value if isinstance(value, (int, float)) and not isinstance(value, bool) else 0


def _item(raw):
    if not isinstance(raw, dict) or not isinstance(raw.get("selector"), str) or not raw["selector"].strip():
        return None
    vsrc = _text(raw.get("vsrc"), 300) or None
    vgen = _text(raw.get("vgen"), 80) or None
    count = raw.get("same_vsrc_count")
    count = count if isinstance(count, int) and not isinstance(count, bool) and count >= 0 else 0
    item = {
        "selector": raw["selector"][:500], "tag": (_text(raw.get("tag"), 40) or "").lower(),
        "classes": [c[:60] for c in raw.get("classes", []) if isinstance(c, str)][:12] if isinstance(raw.get("classes"), list) else [],
        "text": _text(raw.get("text"), MAX_TEXT) or "",
        "box": {key: _number((raw.get("box") or {}).get(key)) for key in _BOX} if isinstance(raw.get("box"), dict) else dict.fromkeys(_BOX, 0),
        "computed": {str(k)[:40]: str(v)[:120] for k, v in list(raw["computed"].items())[:16]} if isinstance(raw.get("computed"), dict) else {},
        "vsrc": vsrc, "vgen": vgen, "same_vsrc_count": count, "own_vsrc": raw.get("own_vsrc") is True,
        "html": _text(raw.get("html"), MAX_HTML) or "", "revision": _text(raw.get("revision"), 64) or None,
        "expired": raw.get("expired") is True, "index": raw["index"] if isinstance(raw.get("index"), int) and not isinstance(raw.get("index"), bool) else 0,
        "parent": _text(raw.get("parent"), 120) or "",
    }
    clip = raw.get("clip")
    if isinstance(clip, dict) and isinstance(clip.get("data_url"), str) and clip["data_url"].startswith("data:image/") and len(clip["data_url"]) <= MAX_CLIP:
        item["clip"] = {"mime": clip["data_url"][5:clip["data_url"].index(";")] if ";" in clip["data_url"] else "image/png", "w": _number(clip.get("w")),
                        "h": _number(clip.get("h")), "bytes": len(clip["data_url"]) * 3 // 4, "data_url": clip["data_url"],
                        "omitted": [o[:120] for o in clip["omitted"][:8] if isinstance(o, str)] if isinstance(clip.get("omitted"), list) else []}
        if item["clip"]["omitted"]:
            item["clip_note"] = "The clip is not complete: it leaves out " + "; ".join(item["clip"]["omitted"]) + "."
    if item["expired"]:
        item["note"] = "Expired: the revision now served no longer has this same element (tag, text and place). Select it again."
    if vsrc:
        file, _, rest = vsrc.partition(":")
        line, _, column = rest.partition(":")
        if line.isdigit() and column.isdigit():
            item.update({"file": file, "line": int(line), "column": int(column)})
    if count > 1 and not item["expired"]:
        item["affects"] = f"{count} elements share this source position"
    if vgen:
        item["generated_by"] = "{{" + vgen + "}}"
        item["note"] = f"Generated by {{{{{vgen}}}}}: change it in the project fields or styles, not in the HTML."
    elif not vsrc and not item["expired"]:
        item["note"] = "No source position: the page did not annotate this element."
    return item


def normalise(selection):
    """Validate a selection reported by the page: bounded, typed, and without items that name no element."""
    if not isinstance(selection, list):
        raise ValueError("selection must be a list")
    return [item for item in map(_item, selection[:MAX_SELECTION]) if item]


def _empty(project_id, revision, note):
    return {"id": project_id, "selection": [], "count": 0, "revision": revision, "updated_ts": None, "note": note}


class StaleSelection(ValueError):
    """The selection names a revision other than the one the open preview serves."""


class PreviewSelections:
    def __init__(self):
        self._lock = threading.Lock()
        self._by_project = {}

    def set(self, project_id, selection, revision=None, session=None):
        items = normalise(selection)
        entry = {"id": project_id, "selection": items, "count": len(items), "revision": revision, "updated_ts": time.time(),
                 "_session": session}
        with self._lock:
            if items:
                self._by_project[project_id] = entry
            else:
                self._by_project.pop(project_id, None)
        return self._public(entry) if items else self.get(project_id, revision)

    def clear(self, project_id):
        with self._lock:
            self._by_project.pop(project_id, None)

    def entry(self, project_id):
        with self._lock:
            return self._by_project.get(project_id)

    @staticmethod
    def _public(entry):
        live = [item for item in entry["selection"] if not item["expired"]]
        out = {key: value for key, value in entry.items() if not key.startswith("_")}
        # Expired items stay visible but are never "the selection": the agent must not act on them.
        return {**out, "selection": live, "count": len(live), "expired": [item for item in entry["selection"] if item["expired"]]}

    def get(self, project_id, revision=None):
        entry = self.entry(project_id)
        if entry:
            return self._public(entry)
        return _empty(project_id, revision, "Nothing is selected in the open preview. The person selects elements with Select on the preview.")


def _running(services, project_id):
    """(revision, session) of the open preview, or None when the project has no running preview. The session is the
    preview process (or its address), so a stop and a new start are different sessions."""
    status = services.app_projects.status(project_id)
    if status.get("state") != "running":
        return None
    return status.get("revision"), status.get("pid") or status.get("url")


def _read(services, project_id, revision=None):
    """Current selection of an existing project's open preview. It is empty once the preview stopped (by the person, an agent or a
    crash), after it restarted, or when it was taken on another revision than the one now served."""
    services.app_projects._directory(project_id)
    store = services.preview_selections
    entry = store.entry(project_id)
    live = _running(services, project_id)
    if entry and (live is None or live[1] != entry["_session"]):
        store.clear(project_id)
        return _empty(project_id, revision, "The preview is not running, so nothing is selected." if live is None
                      else "The preview restarted since the selection was made, so it was dropped.")
    if entry and entry["revision"] and live[0] and entry["revision"] != live[0]:
        return {**_empty(project_id, live[0], "The selection was made on another revision than the preview now serves; the page will report it again once it settles."),
                "stale_revision": entry["revision"], "preview_revision": live[0]}
    return store.get(project_id, revision or (live[0] if live else None))


def read_selection(services, project_id, revision=None, clips=False):
    """What the tool returns: `_read`, with each clip's pixels only when asked for (they are large)."""
    found = copy.deepcopy(_read(services, project_id, revision))  # the store's own items keep their pixels
    if not clips:
        for key in ("selection", "expired"):
            for item in found.get(key, []):
                if "clip" in item:
                    item["clip"] = {name: value for name, value in item["clip"].items() if name != "data_url"}
    return found


def write_selection(services, project_id, selection, revision=None):
    """Store what the preview page reported. A report for a stopped preview is dropped, and one that names another revision than the
    preview serves is refused (StaleSelection)."""
    services.app_projects._directory(project_id)
    live = _running(services, project_id)
    if live is None:
        services.preview_selections.clear(project_id)
        return services.preview_selections.get(project_id, revision)
    items = normalise(selection)
    current = [item for item in items if not item["expired"]]
    if current and not revision:
        raise ValueError("A selection needs the revision the preview page was served from")
    if revision and live[0] and revision != live[0]:
        raise StaleSelection(f"The selection is from revision {revision}; the preview serves {live[0]}")
    if any(item["revision"] and item["revision"] != revision for item in current):
        raise StaleSelection("An element of the selection names another revision than the report")
    return services.preview_selections.set(project_id, selection, revision, live[1])
