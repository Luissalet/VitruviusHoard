"""Instrument factory: a typed spec becomes an App Project that exports as a standalone bundle.

The generated bundle needs only Python's standard library. Its ``server.py`` is ``instrument_runtime.py`` itself, so the
computation Vitruvius shows, the exported instrument and the explainer are the same code.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
import zipfile
from pathlib import Path
from urllib.parse import urlencode

from . import instrument_runtime as runtime
from .instrument_page import PAGE

TEMPLATE = "instrument"
_FIELD_TYPE = {"number": "number", "integer": "number", "text": "text", "choice": "choice", "boolean": "boolean"}


def _slug(text):
    return re.sub(r"[^a-z0-9]+", "_", str(text).lower()).strip("_")[:40] or "case"


def _invalid_cases(spec):
    """Inputs that must be refused, derived from the declared types and ranges."""
    base = {}
    for f in spec["inputs"]:
        if "default" in f:
            base[f["name"]] = f["default"]
    for example in spec["examples"][:1]:
        base.update(example["inputs"])
    cases = []
    for f in spec["inputs"]:
        n = f["name"]
        if f["type"] in ("number", "integer"):
            cases.append({"name": f"{n} is text", "field": n, "values": {**base, n: "abc"}})
            if "min" in f:
                cases.append({"name": f"{n} below minimum", "field": n, "values": {**base, n: f["min"] - 1}})
            if "max" in f:
                cases.append({"name": f"{n} above maximum", "field": n, "values": {**base, n: f["max"] + 1}})
            if f["type"] == "integer":
                cases.append({"name": f"{n} not whole", "field": n, "values": {**base, n: 1.5}})
        elif f["type"] == "choice":
            cases.append({"name": f"{n} not a choice", "field": n, "values": {**base, n: "__no_such_choice__"}})
        elif f["type"] == "boolean":
            cases.append({"name": f"{n} not boolean", "field": n, "values": {**base, n: "maybe"}})
        else:
            cases.append({"name": f"{n} not text", "field": n, "values": {**base, n: 12345}})
        if f.get("required", True) and "default" not in f:
            cases.append({"name": f"{n} missing", "field": n, "values": {k: v for k, v in base.items() if k != n}})
    cases.append({"name": "unknown input", "field": "zz_unknown", "values": {**base, "zz_unknown": 1}})
    return cases


def _tests_source(spec):
    literal = lambda data: repr(json.dumps(data, ensure_ascii=True, sort_keys=True))  # noqa: E731
    lines = [
        '"""Generated by Vitruvius from instrument.json; regenerate rather than editing. Run: python tests/test_instrument.py"""',
        "import html", "import json", "import re", "import sys", "import unittest", "from pathlib import Path", "",
        "ROOT = Path(__file__).resolve().parent.parent", "sys.path.insert(0, str(ROOT))", "import server  # the instrument runtime", "",
        'SPEC = server.validate_instrument_spec(json.loads((ROOT / "instrument.json").read_text(encoding="utf-8")))', "", "",
        "class InstrumentTests(unittest.TestCase):",
        "    def test_spec_is_valid(self):", "        self.assertTrue(SPEC['outputs'])", "",
        "    def refused(self, values, field):",
        "        with self.assertRaises(server.InputError) as caught:", "            server.compute(SPEC, values)",
        "        self.assertIn(field, [e['field'] for e in caught.exception.errors])", "",
        "    def explained(self, values):",
        "        page = server.explain_html(SPEC, values)",
        "        shown = {m.group(1): json.loads(html.unescape(m.group(3))) for m in re.finditer(r'<output data-name=\"([^\"]+)\" data-kind=\"(input|step|output)\" data-value=\"([^\"]*)\"', page)}",
        "        result = server.compute(SPEC, values)",
        "        for row in result['steps'] + result['outputs']:",
        "            self.assertEqual(shown[row['name']], row['value'], row['name'])", "",
    ]
    for index, example in enumerate(spec["examples"], 1):
        name = f"test_example_{index}_{_slug(example['name'])}"
        lines += [f"    def {name}(self):", f"        example = json.loads({literal(example)})",
                  "        result = server.compute(SPEC, example['inputs'])",
                  "        got = {o['name']: o['value'] for o in result['outputs']}",
                  "        self.assertEqual(server.match_expected(example, got), [], got)",
                  "        self.explained(example['inputs'])", ""]
    for index, case in enumerate(_invalid_cases(spec), 1):
        lines += [f"    def test_invalid_{index}_{_slug(case['name'])}(self):", f"        values = json.loads({literal(case['values'])})",
                  f"        self.refused(values, {case['field']!r})", ""]
    for index, inv in enumerate(spec["invariants"], 1):
        if spec["examples"]:
            lines += [f"    def test_invariant_{index}_{_slug(inv['name'])}(self):",
                      f"        for example in json.loads({literal(spec['examples'])}):",
                      "            result = server.compute(SPEC, example['inputs'])",
                      f"            held = [i['holds'] for i in result['invariants'] if i['name'] == {inv['name']!r}]",
                      "            self.assertEqual(held, [True], example['name'])", ""]
    lines += ["", 'if __name__ == "__main__":', "    unittest.main()", ""]
    return "\n".join(lines)


def build_files(spec):
    fields = [{"name": f["name"], "label": f["label"], "type": _FIELD_TYPE[f["type"]], "required": f.get("required", True),
               **({"choices": f["choices"]} if f["type"] == "choice" else {})} for f in spec["inputs"]]
    project = {"format": "vitruvius-app/v1", "name": spec["name"], "description": spec["description"], "fields": fields, "template": TEMPLATE}
    return {
        "project.json": json.dumps(project, ensure_ascii=False, indent=2) + "\n",
        "instrument.json": json.dumps(spec, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        "server.py": Path(runtime.__file__).read_text(encoding="utf-8"),
        "layout.html": "<!doctype html><title>{{name}}</title>{{content}}",
        "pages/index.html": PAGE,
        "tests/test_instrument.py": _tests_source(spec),
        "LICENSE": Path(__file__).with_name("LICENSE").read_text(encoding="utf-8"),
        "README.md": (f"# {spec['name']}\n\nA {spec['kind']} generated from `instrument.json`.\n\n"
                      "Run `python server.py --port 3000` and open http://127.0.0.1:3000 (Python 3.10+, standard library only; no model, "
                      "no network). `/explain` shows a worked example with every intermediate value; `/api/compute` and `/api/spec` "
                      "expose the same computation as JSON.\n\nTests: `python tests/test_instrument.py`. Edit `instrument.json` and "
                      "regenerate in Vitruvius (or re-run the generator) to change the instrument; the formulas live only in the spec.\n"),
    }


def _spec_of(project):
    return runtime.validate_instrument_spec(json.loads(project["files"]["instrument.json"]))


class Instruments:
    def __init__(self, app_projects):
        self.projects = app_projects

    def _project(self, id, revision=None):
        project = self.projects.get(id, revision)
        if project.get("template") != TEMPLATE or "instrument.json" not in project["files"]:
            raise LookupError("Instrument not found")
        return project

    def _summary(self, project, with_spec=True):
        spec = _spec_of(project)
        examples = runtime.check_examples(spec)
        row = {"id": project["id"], "name": spec["name"], "kind": spec["kind"], "revision": project["selected_revision"],
               "current_revision": project["revision"], "revisions": project["revisions"], "inputs": [f["name"] for f in spec["inputs"]],
               "outputs": [o["name"] for o in spec["outputs"]], "examples_ok": all(e["ok"] for e in examples) if examples else None,
               "updated_ts": project["updated_ts"]}
        if with_spec:
            row.update(spec=spec, examples=examples)
        return row

    def create(self, spec):
        spec = runtime.validate_instrument_spec(spec)
        project = self.projects.create_from_files(spec["name"], TEMPLATE, build_files(spec))
        return self._report(project, spec)

    def _report(self, project, spec):
        examples = runtime.check_examples(spec)
        failing = [e for e in examples if not e["ok"]]
        out = self._summary(project)
        out["project_id"] = project["id"]
        out["warnings"] = ([f"{len(failing)} of {len(examples)} spec examples are not satisfied by the formulas; the generated tests will fail until the formula or the expected values change: "
                            + "; ".join(f"{e['name']} ({e.get('error') or ', '.join(m['output'] + ' expected ' + str(m['expected']) + ' got ' + str(m['got']) for m in e['mismatches'])})" for e in failing)]
                           if failing else []) + ([] if examples else ["The spec has no examples, so nothing proves the formulas."])
        return out

    def list(self):
        rows = []
        for item in self.projects.list():
            if item.get("template") != TEMPLATE:
                continue
            try:
                rows.append(self._summary(self.projects.get(item["id"])))
            except (LookupError, ValueError, KeyError):
                continue
        return rows

    def get(self, id, revision=None, include_files=False):
        project = self._project(id, revision)
        out = self._summary(project)
        out["files"] = project["files"] if include_files else sorted(project["files"])
        out["source_sha256"] = project["source_sha256"]
        return out

    def update(self, id, spec):
        """Regenerate the instrument from a changed spec as a new retained revision."""
        current = self._project(id)
        spec = runtime.validate_instrument_spec(spec)
        project = self.projects.update(id, build_files(spec), current["revision"])
        return self._report(project, spec)

    def compute(self, id, inputs, revision=None):
        return runtime.compute(_spec_of(self._project(id, revision)), inputs)

    def explain(self, id, inputs=None, revision=None):
        spec = _spec_of(self._project(id, revision))
        if inputs is None:
            if not spec["examples"]:
                raise ValueError("Give inputs: this instrument has no example to start from")
            inputs = spec["examples"][0]["inputs"]
        data = runtime.explain(spec, inputs)
        return {"id": id, "name": spec["name"], "inputs": data["inputs"], "shown": data["shown"], "invariants": data["invariants"],
                "html_path": "/explain?" + urlencode({k: (str(v).lower() if isinstance(v, bool) else v) for k, v in data["inputs"].items()}),
                "note": "Computed by the same code as the exported instrument; instrument_check proves the exported bundle shows these numbers."}

    # ---------------- run the exported bundle ----------------
    def check(self, id, revision=None, inputs=None, timeout_s=45):
        """Export the instrument, extract it elsewhere and run its tests and server as a user would, with no Vitruvius import."""
        project = self._project(id, revision)
        spec = _spec_of(project)
        exported = self.projects.export(id, project["selected_revision"])
        report = {"id": id, "revision": project["selected_revision"], "export": {"path": exported["path"], "sha256": exported["sha256"]},
                  "tests": None, "examples": [], "explainer": [], "page_ok": False, "ok": False}
        with tempfile.TemporaryDirectory(prefix="instrument-check-", ignore_cleanup_errors=True) as temporary:
            root = Path(temporary)
            with zipfile.ZipFile(exported["path"]) as bundle:
                bundle.extractall(root)
            flags = getattr(subprocess, "CREATE_NO_WINDOW", 0)
            test = subprocess.run([sys.executable, "-I", "tests/test_instrument.py"], cwd=root, capture_output=True, text=True, timeout=timeout_s, creationflags=flags)
            ran = re.search(r"Ran (\d+) tests?", test.stderr)
            report["tests"] = {"ok": test.returncode == 0, "ran": int(ran.group(1)) if ran else 0, "output": (test.stderr + test.stdout)[-1500:] if test.returncode else ""}
            ready = root / "ready.json"
            log = (root / "server.log").open("wb")
            process = subprocess.Popen([sys.executable, "-I", "server.py", "--port", "0", "--ready-file", str(ready)], cwd=root, stdout=log, stderr=log, creationflags=flags)
            try:
                deadline = time.monotonic() + timeout_s
                while not ready.exists() and process.poll() is None and time.monotonic() < deadline:
                    time.sleep(.02)
                if not ready.exists():
                    raise ValueError("The exported instrument did not start: " + (root / "server.log").read_text(encoding="utf-8", errors="replace")[-800:])
                base = json.loads(ready.read_text(encoding="utf-8"))["url"]

                def call(path, body=None):
                    request = urllib.request.Request(base + path, data=json.dumps(body).encode() if body is not None else None,
                                                     headers={"Content-Type": "application/json"}, method="POST" if body is not None else "GET")
                    with urllib.request.urlopen(request, timeout=10) as response:
                        return response.read()
                import html as _page_html
                page = call("/").decode("utf-8", "replace")
                report["page_ok"] = _page_html.escape(spec["name"]) in page and 'id="spec"' in page
                for example in spec["examples"]:
                    try:
                        result = json.loads(call("/api/compute", example["inputs"]))
                        bad = runtime.match_expected(example, {o["name"]: o["value"] for o in result["outputs"]})
                        report["examples"].append({"name": example["name"], "ok": not bad, "mismatches": bad})
                    except urllib.error.HTTPError as error:
                        report["examples"].append({"name": example["name"], "ok": False, "error": json.loads(error.read()).get("error", str(error)), "mismatches": []})
                cases = [(e["name"], e["inputs"]) for e in spec["examples"]] + ([("given inputs", inputs)] if inputs else [])
                for name, values in cases:
                    report["explainer"].append(self._explainer_parity(spec, name, values, call))
            finally:
                if os.name == "nt":
                    # A venv python.exe is a launcher: stop the whole tree or the real
                    # interpreter keeps server.log open and the folder cannot be removed.
                    subprocess.run(["taskkill", "/F", "/T", "/PID", str(process.pid)], stdin=subprocess.DEVNULL,
                                   capture_output=True, creationflags=flags)
                else:
                    process.terminate()
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
                log.close()
        report["ok"] = bool(report["tests"]["ok"] and all(e["ok"] for e in report["examples"]) and all(e["ok"] for e in report["explainer"]))
        report["examples_ok"] = all(e["ok"] for e in report["examples"])
        report["explainer_matches_outputs"] = all(e["ok"] for e in report["explainer"])
        if not spec["examples"]:
            report["warning"] = "The spec has no examples, so nothing proves the formulas."
        return report

    @staticmethod
    def _explainer_parity(spec, name, values, call):
        query = urlencode({k: (str(v).lower() if isinstance(v, bool) else v) for k, v in values.items()})
        try:
            page = call("/explain?" + query).decode("utf-8")
            result = json.loads(call("/api/compute", values))
        except urllib.error.HTTPError as error:
            return {"name": name, "ok": False, "error": error.read().decode("utf-8", "replace")[:200], "mismatches": []}
        import html as _html
        shown = {m.group(1): json.loads(_html.unescape(m.group(3))) for m in re.finditer(r'<output data-name="([^"]+)" data-kind="(input|step|output)" data-value="([^"]*)"', page)}
        host = runtime.compute(spec, values)
        mismatches = []
        for row in result["steps"] + result["outputs"]:
            if shown.get(row["name"]) != row["value"]:
                mismatches.append({"quantity": row["name"], "explainer": shown.get(row["name"]), "exported_instrument": row["value"]})
            expected = next(r["value"] for r in host["steps"] + host["outputs"] if r["name"] == row["name"])
            if expected != row["value"]:
                mismatches.append({"quantity": row["name"], "host": expected, "exported_instrument": row["value"]})
        return {"name": name, "ok": not mismatches, "numbers_compared": len(result["steps"]) + len(result["outputs"]), "mismatches": mismatches}

    def export(self, id, revision=None, run_check=True):
        project = self._project(id, revision)
        if run_check:
            report = self.check(id, project["selected_revision"])
            return {"id": id, "revision": report["revision"], **report["export"], "check": {k: report[k] for k in ("ok", "examples_ok", "explainer_matches_outputs")}, "tests": report["tests"]}
        return self.projects.export(id, project["selected_revision"])
