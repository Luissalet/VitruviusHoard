def blender_script(model: str, out_dir: str, views: list[dict] | None = None, *, section_axis: str = "z", section_view: int = 0,
                   engine: str = "CYCLES", samples: int = 24, width: int = 1600, height: int = 900, fps: int = 24, seconds: int = 8,
                   section: bool = True) -> str:
    views = [dict(v) for v in (views or DEFAULT_VIEWS)]
    for v in views:
        for key, default in (("azimuth", 35), ("elevation", 18), ("distance", 1.9), ("lens", 42)):
            v[key] = float(v.get(key, default))
        v["name"] = "".join(ch if ch.isalnum() or ch in "-_" else "-" for ch in str(v.get("name") or "vista")) or "vista"
    if section_axis not in {"x", "y", "z"}:
        raise ValueError("section_axis must be x, y or z")
    if not 0 <= section_view < len(views):
        raise ValueError("section_view must index one of the views")
    if engine not in {"CYCLES", "EEVEE", "WORKBENCH"}:
        raise ValueError("engine must be CYCLES, EEVEE or WORKBENCH")
    config = {"model": model, "out_dir": out_dir, "views": views, "engine": engine, "samples": int(samples), "width": int(width), "height": int(height),
              "fps": int(fps), "seconds": int(seconds), "section": {"enabled": bool(section), "axis": section_axis, "view": int(section_view)}}
    return _TEMPLATE.replace("__CONFIG__", repr(json.dumps(config, ensure_ascii=False)))


def site_page(title: str, subtitle: str, views: list[dict], video: str | None = "corte-de-seccion.mp4") -> dict:
    """The one-page site around the rendered files (relative paths: put the page next to them)."""
    views = views or DEFAULT_VIEWS
    hero = html.escape(views[0]["name"]) + ".png"
    rest = "".join(f'<figure class="v"><img src="{html.escape(v["name"])}.png" alt="Vista {html.escape(v["name"].replace("-", " "))} del modelo" loading="lazy" width="1600" height="900"></figure>' for v in views[1:])
    clip = (f'<section class="cut" aria-labelledby="corte"><h2 id="corte">Por dentro</h2><video src="{html.escape(video)}" muted loop playsinline preload="metadata" aria-label="Corte de sección recorriendo el modelo"></video></section>' if video else "")
    css = (".hero{position:relative;min-height:100svh;display:grid;align-content:end;padding:clamp(24px,6vw,96px);color:#f9fafb;background:#222 url(" + hero + ") center/cover}"
           ".hero::before{content:\"\";position:absolute;inset:0;background:linear-gradient(transparent 40%,#0b0d10aa)}.hero>*{position:relative}"
           ".hero h1{font-size:clamp(52px,9vw,140px);max-width:14ch}.hero p{max-width:44ch;font-size:clamp(17px,1.6vw,22px);margin-top:16px}"
           ".cut{padding:clamp(40px,8vw,120px) clamp(24px,6vw,96px)}.cut h2{font-size:clamp(36px,5vw,72px);margin-bottom:24px}.cut video{width:100%;max-height:80vh;object-fit:cover;border-radius:6px;background:#0b0d10}"
           ".gal{display:grid;gap:clamp(16px,3vw,40px);padding:0 clamp(24px,6vw,96px) 96px}.v{margin:0}.v img{width:100%;height:auto;display:block;border-radius:6px}"
           "@supports (animation-timeline:view()){.v{animation:rise linear both;animation-timeline:view();animation-range:entry 0% cover 30%}@keyframes rise{from{opacity:0;translate:0 48px}}}")
    body = (f'<header class="hero"><h1>{html.escape(title)}</h1><p>{html.escape(subtitle)}</p></header>{clip}<main class="gal" aria-label="Vistas">{rest}</main>')
    script = ("var v=document.querySelector('video');if(v&&!matchMedia('(prefers-reduced-motion: reduce)').matches){new IntersectionObserver(function(e){e.forEach(function(x){x.isIntersecting?v.play():v.pause()})},{threshold:.4}).observe(v)}") if video else ""
    return pages.document(title, css, body, script)
