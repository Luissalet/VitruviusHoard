def specs_for(pack: str) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    if pack in ("slop", "quality", "craft"):
        table = {"slop": _SLOP, "quality": _QUALITY, "craft": _CRAFT}[pack]
        for name_id, engine, scope, severity, name, description, fix, source_id in table:
            # upstream ids that are plain words came from impeccable, numbers from hallmark gates
            source = "hallmark" if (source_id[:1].isdigit() or source_id.startswith("F")) else "impeccable"
            out.append({"name_id": name_id, "engine": engine, "scope": scope, "severity": severity, "name": name,
                        "description": description, "fix": fix, "source": source, "source_id": source_id,
                        "reference": f"{source} {'gate ' if source == 'hallmark' else ''}{source_id}"})
    elif pack == "visual":
        for name_id, source_id, name, description in _VISUAL:
            out.append({"name_id": name_id, "engine": "visual", "scope": "layout", "severity": "warning", "name": name,
                        "description": description, "fix": "Judged from the screenshots by the vision model.",
                        "source": "hallmark", "source_id": source_id, "judged": True, "reference": f"hallmark gate {source_id}"})
    elif pack == "ds":
        for name_id, scope, severity, name, description, fix in _DS:
            aliases = ()
            if name_id in ("font", "color", "radius"):
                aliases = (f"design-system-{name_id}",)
            elif name_id == "scale":
                aliases = ("design-system-font-size", "design-system-scale")
            else:
                aliases = ("design-system-spacing",)
            out.append({"name_id": name_id, "engine": "browser", "scope": scope, "severity": severity, "name": name,
                        "description": description, "fix": fix, "source": "impeccable" if name_id != "spacing" else "hallmark",
                        "source_id": f"design-system-{name_id}" if name_id != "scale" else "design-system-font-size",
                        "reference": "impeccable design-system-*; compares the page with a tokens_get system", "aliases": aliases})
    return out


