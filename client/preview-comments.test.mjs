import test from "node:test";
import assert from "node:assert/strict";
import { anchorChanges, copilotComments, groupComments, isCommentMessage, pinsFor, sameComments, sourceLine, statusLabel, targetName } from "./src/preview-comments.js";

const make = (id, n, status, extra = {}) => ({ id, n, status, note: "Make it bigger", page: "/", selector: "main > h1", vsrc: "pages/index.html:3:5", tag: "h1", classes: ["title"], anchor: { state: "ok", vsrc: "pages/index.html:3:5" }, updated_ts: n, ...extra });

test("only comment messages from the preview frame with the inspector envelope are accepted", () => {
  const frame = {};
  const good = { source: frame, origin: "http://127.0.0.1:9", data: { hoardDock: 1, type: "dock/comment-target", page: "/", element: {} } };
  assert.equal(isCommentMessage(good, frame, "http://127.0.0.1:9"), true);
  assert.equal(isCommentMessage({ ...good, origin: "http://evil.test" }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isCommentMessage({ ...good, source: {} }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isCommentMessage({ ...good, data: { ...good.data, type: "dock/select" } }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isCommentMessage({ ...good, data: { ...good.data, hoardDock: 2 } }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isCommentMessage(good, null, "http://127.0.0.1:9"), false);
});

test("statuses read in Spanish and English", () => {
  assert.equal(statusLabel("seen", true), "Vista por el agente");
  assert.equal(statusLabel("answered", false), "Answered");
  assert.equal(statusLabel("resolved", true), "Resuelta");
});

test("comments without anchor stay in their own list, closed ones apart", () => {
  const list = [make("c1", 1, "pending"), make("c2", 2, "seen", { anchor: { state: "lost" } }), make("c3", 3, "resolved"), make("c4", 4, "answered")];
  const { anchored, lost, closed } = groupComments(list);
  assert.deepEqual(anchored.map((c) => c.id), ["c1", "c4"]);
  assert.deepEqual(lost.map((c) => c.id), ["c2"]);
  assert.deepEqual(closed.map((c) => c.id), ["c3"]);
});

test("the preview gets this page's pins with what it needs to find them", () => {
  const list = [make("c1", 1, "pending"), make("c2", 2, "seen", { page: "/about", anchor: { state: "ok", vsrc: "pages/about.html:1:1" } }), make("c3", 3, "resolved", { anchor: { state: "ok", vsrc: "pages/index.html:9:1" } })];
  assert.deepEqual(pinsFor(list, "/"), [
    { id: "c1", n: 1, status: "pending", selector: "main > h1", vsrc: "pages/index.html:3:5" },
    { id: "c3", n: 3, status: "resolved", selector: "main > h1", vsrc: "pages/index.html:9:1" },
  ]);
  assert.equal(pinsFor(list, "/nowhere").length, 0);
});

test("only anchors that differ from what is stored are sent back", () => {
  const list = [make("c1", 1, "pending"), make("c2", 2, "pending", { anchor: { state: "lost" } })];
  const reported = [
    { id: "c1", state: "ok", vsrc: "pages/index.html:3:5" }, // same
    { id: "c2", state: "lost" }, // same
    { id: "c1", state: "lost" }, { id: "c2", state: "ok", vsrc: "pages/index.html:4:1" }, // changed
    { id: "zz", state: "lost" }, { id: "c1", state: "maybe" },
  ];
  assert.deepEqual(anchorChanges(list, reported).map((a) => a.id + ":" + a.state), ["c1:lost", "c2:ok"]);
  assert.deepEqual(anchorChanges(list, null), []);
});

test("the copilot sees the comments waiting for the agent, briefly", () => {
  const list = [make("c1", 1, "pending", { note: "x".repeat(300) }), make("c2", 2, "seen", { anchor: { state: "lost" } }), make("c3", 3, "answered"), make("c4", 4, "resolved"), make("c5", 5, "pending", { stale: true, revision: "r1" })];
  const seen = copilotComments(list);
  assert.deepEqual(seen.map((c) => c.id), ["c1", "c2", "c5"]);
  assert.equal(seen[0].note.length, 200);
  assert.equal(seen[1].anchor, "lost");
  assert.equal(seen[2].revision, "r1");
  assert.equal(copilotComments(Array.from({ length: 30 }, (_, i) => make("c" + i, i, "pending"))).length, 12);
});

test("lines and names describe where a comment lives", () => {
  assert.equal(sourceLine(make("c1", 1, "pending"), true), "pages/index.html:3:5");
  assert.equal(sourceLine({ vgen: "table" }, false), "generated by {{table}}");
  assert.equal(sourceLine({}, true), "sin posición en el fuente");
  assert.equal(targetName(make("c1", 1, "pending")), "h1.title");
});

test("a poll result is applied only when something changed", () => {
  const a = [make("c1", 1, "pending")];
  assert.equal(sameComments(a, [make("c1", 1, "pending")]), true);
  assert.equal(sameComments(a, [make("c1", 1, "pending", { updated_ts: 9 })]), false);
  assert.equal(sameComments(a, [make("c1", 1, "pending", { anchor: { state: "lost" } })]), false);
  assert.equal(sameComments(a, []), false);
});
