// Pure helpers for the "Select" mode of the application preview (no DOM or React: they run under `node --test`).

/** Message types the inspector inside the preview sends to this page, and the ones this page sends back. */
export const FROM_PAGE = ["dock/select", "dock/inspector-ready"];

/** True for a message that really comes from the preview frame: right window, right origin, right envelope. */
export function isInspectorMessage(event, frameWindow, origin) {
  const data = event && event.data;
  return Boolean(frameWindow) && event.source === frameWindow && event.origin === origin
    && data && data.hoardDock === 1 && FROM_PAGE.includes(data.type) && Array.isArray(data.selection);
}

/** `tag.class` of a selected element, e.g. `button.primary`. */
export function elementName(item) {
  return (item.tag || "element") + (item.classes && item.classes.length ? "." + item.classes.slice(0, 2).join(".") : "");
}

/** Short line for a chip: name, trimmed text and where it comes from. */
export function chipText(item, index) {
  const text = item.text ? ` "${item.text.length > 32 ? item.text.slice(0, 31) + "…" : item.text}"` : "";
  return `${index + 1}. ${elementName(item)}${text}`;
}

/** Where the element lives in the source, or what generated it; `null` when the page did not say. */
export function sourceText(item, es) {
  if (item.vgen) return es ? `generado por {{${item.vgen}}}` : `generated by {{${item.vgen}}}`;
  if (!item.vsrc) return null;
  return item.vsrc;
}

/** The "affects N elements" note for repeated elements. */
export function affectsText(item, es) {
  const count = item.same_vsrc_count || 0;
  if (count <= 1) return null;
  return es ? `afecta a ${count} elementos` : `affects ${count} elements`;
}

/** What the copilot sees of the selection: a bounded card per element. The tool returns the full detail. */
export function copilotSelection(items, limit = 8) {
  return items.slice(0, limit).map((item) => ({
    selector: item.selector, tag: item.tag, ...(item.classes && item.classes.length ? { classes: item.classes } : {}),
    ...(item.vsrc ? { source: item.vsrc } : {}), ...(item.vgen ? { generated_by: `{{${item.vgen}}}` } : {}),
    ...(item.text ? { text: item.text.slice(0, 120) } : {}), ...(item.same_vsrc_count > 1 ? { affects: item.same_vsrc_count } : {}),
    ...(item.revision ? { revision: item.revision } : {}), ...(item.expired ? { expired: true } : {}),
    ...(item.box ? { box: item.box } : {}), ...(item.clip ? { clip: { mime: item.clip.mime, w: item.clip.w, h: item.clip.h, bytes: item.clip.bytes, omitted: item.clip.omitted || [] } } : {}),
    ...(item.html ? { html: item.html.slice(0, 300) } : {}),
    ...(item.computed ? { styles: Object.fromEntries(["color", "backgroundColor", "fontSize", "fontWeight", "margin", "padding", "display"].filter((key) => item.computed[key]).map((key) => [key, item.computed[key]])) } : {}),
  }));
}

/** What a freshly loaded page needs to find the same elements again: identity, not position alone. */
export function identitiesOf(items) {
  return items.map(({ selector, tag, text, vsrc, own_vsrc, parent, index, near, anchor, revision, expired, classes, vgen, box }) => (
    { selector, tag, text, vsrc, own_vsrc, parent, index, near, anchor, revision, expired, classes, vgen, box })).filter((item) => item.selector);
}
