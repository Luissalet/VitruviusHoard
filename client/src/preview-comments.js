// Pure helpers for the pinned comments of the application preview (no DOM or React: they run under `node --test`).

/** Message types the inspector sends about comments. */
export const COMMENT_FROM_PAGE = ["dock/comment-target", "dock/comment-anchors", "dock/comment-focus"];

/** True for a comment message that really comes from the preview frame: right window, right origin, right envelope. */
export function isCommentMessage(event, frameWindow, origin) {
  const data = event && event.data;
  return Boolean(frameWindow) && event.source === frameWindow && event.origin === origin
    && Boolean(data) && data.hoardDock === 1 && COMMENT_FROM_PAGE.includes(data.type);
}

export const STATUSES = ["pending", "seen", "answered", "resolved", "dismissed"];
const LABELS = {
  pending: ["Pendiente", "Pending"], seen: ["Vista por el agente", "Seen by the agent"], answered: ["Contestada", "Answered"],
  resolved: ["Resuelta", "Resolved"], dismissed: ["Descartada", "Dismissed"],
};

/** The status as a person reads it. */
export function statusLabel(status, es) {
  return (LABELS[status] || [status, status])[es ? 0 : 1];
}

/** Still needs something from someone: the agent (pending, seen) or the person (answered). */
export const isOpen = (comment) => ["pending", "seen", "answered"].includes(comment.status);

/** A pin whose element the page no longer finds: it stays in its own list. */
export const isLost = (comment) => comment.anchor?.state === "lost";

/** Split a project's comments into open and closed ones, and those without anchor (kept apart, still listed). */
export function groupComments(comments) {
  const open = comments.filter(isOpen);
  return {
    anchored: open.filter((comment) => !isLost(comment)),
    lost: comments.filter(isLost),
    closed: comments.filter((comment) => !isOpen(comment) && !isLost(comment)),
  };
}

/** What the preview needs to find a pin: the identity recorded when the comment was made (source position, selector, tag, text) and the revision it was made on. */
export function pinsFor(comments, page) {
  return comments.filter((comment) => comment.page === page).map((comment) => ({
    id: comment.id, n: comment.n, status: comment.status, selector: comment.selector, vsrc: comment.vsrc || "", own_vsrc: Boolean(comment.own_vsrc),
    tag: comment.tag || "", text: comment.element_text || "", revision: comment.revision || "",
    attrs: comment.attrs || {}, parent: comment.parent || "", index: comment.index || 0,
  }));
}

/** Anchors the page reported (on `revision`) that differ from what is stored: the only ones worth sending. */
export function anchorChanges(comments, anchors, revision) {
  const byId = new Map(comments.map((comment) => [comment.id, comment]));
  return (Array.isArray(anchors) ? anchors : []).filter((anchor) => {
    const comment = byId.get(anchor.id);
    if (!comment || (anchor.state !== "ok" && anchor.state !== "lost")) return false;
    const stored = comment.anchor || {};
    return stored.state !== anchor.state || stored.revision !== revision || (anchor.state === "ok" && (stored.vsrc || null) !== (anchor.vsrc || null));
  });
}

/** Where the comment was made, in one line. */
export function sourceLine(comment, es) {
  if (comment.vgen) return es ? `generado por {{${comment.vgen}}}` : `generated by {{${comment.vgen}}}`;
  return comment.vsrc || (es ? "sin posición en el fuente" : "no source position");
}

/** `tag.class` of the element the comment is pinned to. */
export function targetName(comment) {
  return (comment.tag || "element") + (comment.classes && comment.classes.length ? "." + comment.classes.slice(0, 2).join(".") : "");
}

/** What the copilot sees of the comments waiting for the agent: small, so it fits the turn context. */
export function copilotComments(comments, limit = 12) {
  return comments.filter((comment) => comment.status === "pending" || comment.status === "seen").slice(0, limit).map((comment) => ({
    id: comment.id, status: comment.status, note: comment.note.slice(0, 200), selector: comment.selector,
    ...(comment.vsrc ? { source: comment.vsrc } : {}), ...(isLost(comment) ? { anchor: "lost" } : {}), ...(comment.stale ? { revision: comment.revision } : {}),
  }));
}

/** True when the list shown differs from the new one (poll results are only applied when something changed). */
export function sameComments(a, b) {
  return a.length === b.length && a.every((comment, index) => comment.id === b[index].id && comment.updated_ts === b[index].updated_ts
    && comment.anchor?.state === b[index].anchor?.state && comment.anchor?.vsrc === b[index].anchor?.vsrc);
}
