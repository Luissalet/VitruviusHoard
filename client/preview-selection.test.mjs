import test from "node:test";
import assert from "node:assert/strict";
import { affectsText, chipText, copilotSelection, elementName, identitiesOf, isInspectorMessage, sourceText } from "./src/preview-selection.js";

const item = { selector: "ul > li:nth-of-type(2)", tag: "li", classes: ["row", "odd", "x"], text: "Buy milk and then a very long second sentence", vsrc: "pages/index.html:7:5", same_vsrc_count: 3 };

test("chips name the element, trim its text and report where it comes from", () => {
  assert.equal(elementName(item), "li.row.odd");
  assert.equal(chipText(item, 1), '2. li.row.odd "Buy milk and then a very long s…"');
  assert.equal(sourceText(item, true), "pages/index.html:7:5");
  assert.equal(sourceText({ vgen: "table", vsrc: "pages/index.html:9:1" }, false), "generated by {{table}}");
  assert.equal(sourceText({}, true), null);
  assert.equal(affectsText(item, true), "afecta a 3 elementos");
  assert.equal(affectsText({ same_vsrc_count: 1 }, false), null);
});

test("only messages from the preview frame with the inspector envelope are accepted", () => {
  const frame = {};
  const good = { source: frame, origin: "http://127.0.0.1:9", data: { hoardDock: 1, type: "dock/select", selection: [], mode: true } };
  assert.equal(isInspectorMessage(good, frame, "http://127.0.0.1:9"), true);
  assert.equal(isInspectorMessage({ ...good, origin: "http://evil.test" }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isInspectorMessage({ ...good, source: {} }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isInspectorMessage({ ...good, data: { ...good.data, type: "dock/ready" } }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isInspectorMessage({ ...good, data: { type: "dock/select", selection: [] } }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isInspectorMessage(good, null, "http://127.0.0.1:9"), false);
});

test("the copilot gets a bounded card per element and a reload gets identities back", () => {
  const full = { ...item, revision: "r1", html: "<li>" + "x".repeat(500), computed: { color: "red", gap: "1px", margin: "0px" } };
  const [card] = copilotSelection([full]);
  assert.equal(card.revision, "r1");
  assert.equal(card.source, item.vsrc);
  assert.equal(card.affects, 3);
  assert.equal(card.html.length, 300);
  const [boxed] = copilotSelection([{ ...full, box: { x: 1, y: 2, w: 3, h: 4 }, clip: { mime: "image/png", w: 9, h: 9, bytes: 12, data_url: "data:image/png;base64,AAAA" }, expired: true }]);
  assert.deepEqual(boxed.box, { x: 1, y: 2, w: 3, h: 4 });
  assert.deepEqual(boxed.clip, { mime: "image/png", w: 9, h: 9, bytes: 12, omitted: [] }, "the context carries the clip's description, never its pixels");
  assert.equal(boxed.expired, true);
  assert.deepEqual(card.styles, { color: "red", margin: "0px" });
  assert.equal(copilotSelection(Array.from({ length: 40 }, () => item)).length, 8);
  const [identity] = identitiesOf([{ ...full, own_vsrc: true, parent: "ul|", index: 1, near: ["a", "b"], html: "<li>", computed: {}, clip: { data_url: "data:..." } }, { tag: "p" }]);
  assert.deepEqual(identity, { selector: item.selector, tag: "li", text: item.text, vsrc: item.vsrc, own_vsrc: true, parent: "ul|", index: 1, near: ["a", "b"], anchor: undefined, revision: "r1", expired: undefined, classes: item.classes, vgen: undefined, box: undefined });
  assert.equal(identitiesOf([{ tag: "p" }]).length, 0, "no selector, no identity");
});
