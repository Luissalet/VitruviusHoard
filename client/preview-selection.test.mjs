import test from "node:test";
import assert from "node:assert/strict";
import { affectsText, chipText, copilotSelection, elementName, isInspectorMessage, selectorsOf, sourceText } from "./src/preview-selection.js";

const item = { selector: "ul > li:nth-of-type(2)", tag: "li", classes: ["row", "odd", "x"], text: "Buy milk and then a very long second sentence", vsrc: "pages/index.html:7:5", same_vsrc_count: 3 };

test("chips name the element, trim its text and report where it comes from", () => {
  assert.equal(elementName(item), "li.row.odd");
  assert.equal(chipText(item, 1), '2. li.row.odd "Buy milk and then a very long s…"');
  assert.equal(sourceText(item, true), "pages/index.html:7:5");
  assert.equal(sourceText({ vgen: "table", vsrc: "pages/index.html:9:1" }, false), "generated by {{table}}");
  assert.equal(sourceText({}, true), null);
  assert.equal(affectsText(item, true), "afecta a 3 elementos");
  assert.equal(affectsText({ same_vsrc_count: 1 }, false), null);
});

test("only messages from the preview frame with the inspector envelope are accepted", () => {
  const frame = {};
  const good = { source: frame, origin: "http://127.0.0.1:9", data: { hoardDock: 1, type: "dock/select", selection: [], mode: true } };
  assert.equal(isInspectorMessage(good, frame, "http://127.0.0.1:9"), true);
  assert.equal(isInspectorMessage({ ...good, origin: "http://evil.test" }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isInspectorMessage({ ...good, source: {} }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isInspectorMessage({ ...good, data: { ...good.data, type: "dock/ready" } }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isInspectorMessage({ ...good, data: { type: "dock/select", selection: [] } }, frame, "http://127.0.0.1:9"), false);
  assert.equal(isInspectorMessage(good, null, "http://127.0.0.1:9"), false);
});

test("the copilot gets a small summary and a reload gets the selectors back", () => {
  const [summary] = copilotSelection([item]);
  assert.deepEqual(summary, { selector: item.selector, tag: "li", source: item.vsrc, text: item.text.slice(0, 80), affects: 3 });
  assert.equal(copilotSelection(Array.from({ length: 40 }, () => item)).length, 12);
  assert.deepEqual(selectorsOf([item, { tag: "p" }]), ["ul > li:nth-of-type(2)"]);
});
